/// <summary>
/// Typed service outcome wrapping payload, HTTP-style status code, and error text. Used across
/// chat and channel services instead of throwing for expected validation failures.
/// </summary>
public class ChatResult<T>
{
    /// <summary>True when <see cref="Data"/> is populated and no error occurred.</summary>
    public bool IsSuccess { get; set; }
    /// <summary>Payload on success; null on failure.</summary>
    public T? Data { get; set; }
    /// <summary>Human-readable failure reason when <see cref="IsSuccess"/> is false.</summary>
    public string? ErrorMessage { get; set; }
    /// <summary>Suggested HTTP status for controllers mapping this result.</summary>
    public int StatusCode { get; set; }

    /// <summary>Constructs a 200 success result with data.</summary>
    /// <param name="data">Payload returned to the caller.</param>
    /// <returns>Successful result instance.</returns>
    public static ChatResult<T> Success(T data) => new() { IsSuccess = true, Data = data, StatusCode = 200 };
    /// <summary>Constructs a failed result with message and status code.</summary>
    /// <param name="message">Error text for clients or logs.</param>
    /// <param name="statusCode">HTTP status to propagate.</param>
    /// <returns>Failed result instance with no data.</returns>
    public static ChatResult<T> Failure(string message, int statusCode) => new() { IsSuccess = false, ErrorMessage = message, StatusCode = statusCode };
}

/// <summary>Non-generic <see cref="ChatResult{T}"/> for operations with no response body.</summary>
public class ChatResult
{
    /// <summary>True when the operation completed without error.</summary>
    public bool IsSuccess { get; set; }
    /// <summary>Human-readable failure reason when <see cref="IsSuccess"/> is false.</summary>
    public string? ErrorMessage { get; set; }
    /// <summary>Suggested HTTP status for controllers mapping this result.</summary>
    public int StatusCode { get; set; }

    /// <summary>Constructs a 200 success result with no payload.</summary>
    /// <returns>Successful result instance.</returns>
    public static ChatResult Success() => new() { IsSuccess = true, StatusCode = 200 };
    /// <summary>Constructs a failed result with message and status code.</summary>
    /// <param name="message">Error text for clients or logs.</param>
    /// <param name="statusCode">HTTP status to propagate.</param>
    /// <returns>Failed result instance.</returns>
    public static ChatResult Failure(string message, int statusCode) => new() { IsSuccess = false, ErrorMessage = message, StatusCode = statusCode };
}

