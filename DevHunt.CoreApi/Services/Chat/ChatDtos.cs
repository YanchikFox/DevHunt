using System;
using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.Text.Json.Serialization;

namespace DevHunt.CoreApi.Services.Chat;

/// <summary>
/// DTO for sending a message.
/// </summary>
public class SendMessageDto
{
    /// <summary>
    /// Message content.
    /// </summary>
    [Required]
    [MaxLength(10000)]
    public string Content { get; set; } = string.Empty;

    /// <summary>
    /// ID of the message to reply to (optional).
    /// </summary>
    public Guid? ReplyToId { get; set; }

    /// <summary>
    /// Indicates if this message was generated by AI assistant.
    /// When true, the message is marked as AI-generated for tracking and UI purposes.
    /// </summary>
    public bool IsAiGenerated { get; set; }

    /// <summary>
    /// Server-side AI transparency summary. Not bindable from public JSON.
    /// </summary>
    [JsonIgnore]
    public string? AiMetadataJson { get; set; }

    /// <summary>
    /// Server-side full AI transparency payload. Not bindable from public JSON.
    /// </summary>
    [JsonIgnore]
    public string? AiDetailsJson { get; set; }
}

