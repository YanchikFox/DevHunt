/**
 * Hook to create a new direct conversation with another user.
 * @returns Mutation result for creating a direct conversation.
 */
function useCreateConversation(endpointFn: (id: string) => string) {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: async (id: string) => {
      if (USE_MOCKS) return { conversationId: "mock-id" }
      const response = await apiClient.post<{ conversationId: string }>(endpointFn(id))
      return { conversationId: response.data.conversationId }
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["chat", "conversations"] })
    },
  })
}

export function useCreateDirectConversation() {
  return useCreateConversation((id) => `/chat/conversations/direct/${id}`)
}

export function useCreateProjectConversation() {
  return useCreateConversation((id) => `/chat/conversations/project/${id}`)
}
